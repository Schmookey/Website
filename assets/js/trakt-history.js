/* Trakt watch history and latest-watch card.
   Loads a public JSON snapshot generated by GitHub Actions; no browser-side API credentials.
   All remote strings are inserted with textContent and URLs are restricted. */
(() => {
  "use strict";
  const PROFILE = "https://trakt.tv/users/pat13nt_z3r0";
  const MAX_ENTRIES = 30;
  const SAFE_POSTER = /^https:\/\/image\.tmdb\.org\/t\/p\/w(?:92|154|185|200|300|342|500)\/[A-Za-z0-9._-]+\.(?:jpg|jpeg|png|webp)$/i;

  function allowedLink(value) {
    if (typeof value !== "string") return PROFILE;
    try {
      const u = new URL(value);
      return u.protocol === "https:" && u.hostname === "trakt.tv" && !u.username && !u.password
        ? u.href : PROFILE;
    } catch { return PROFILE; }
  }

  function allowedPoster(value) {
    if (typeof value !== "string") return "";
    if (/^\/assets\/images\/trakt\/[A-Za-z0-9._-]+\.(?:jpg|jpeg|png|webp)$/i.test(value)) return value;
    return SAFE_POSTER.test(value) ? value : "";
  }

  function normalise(entry) {
    if (!entry || typeof entry !== "object") return null;
    const title = typeof entry.title === "string" ? entry.title.trim() : "";
    if (!title) return null;
    const detail = typeof entry.episode === "string" ? entry.episode.trim() : "";
    const type = entry.type === "Movie" ? "Movie" : "TV Show";
    const date = typeof entry.watched_at === "string" ? new Date(entry.watched_at) : null;
    return {
      title, type, detail,
      season: Number.isInteger(entry.season) && entry.season >= 0 ? entry.season : null,
      episodeNumber: Number.isInteger(entry.episode_number) && entry.episode_number >= 0 ? entry.episode_number : null,
      year: Number.isInteger(entry.year) && entry.year > 1900 && entry.year < 2200 ? entry.year : null,
      cover: allowedPoster(entry.cover),
      link: allowedLink(entry.link),
      date: date && !Number.isNaN(date.getTime()) ? date : null,
      updated: typeof entry.updated === "string" ? entry.updated : ""
    };
  }

  function element(tag, className, text) {
    const node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined && text !== null) node.textContent = String(text);
    return node;
  }

  function details(item) {
    const parts = [];
    if (item.type === "TV Show" && item.season !== null && item.episodeNumber !== null) {
      parts.push("S" + String(item.season).padStart(2,"0") + "E" + String(item.episodeNumber).padStart(2,"0"));
    } else if (item.type === "TV Show" && item.season !== null) {
      parts.push("Season " + item.season);
    }
    if (item.detail) parts.push(item.detail);
    if (item.year) parts.push(String(item.year));
    return parts.join(" · ");
  }

  function renderCard(item, compact) {
    const card = element("article", compact ? "trakt-live-card trakt-live-compact" : "trakt-live-card");
    if (item.cover) {
      const cover = element("img","trakt-live-poster");
      cover.src = item.cover;
      cover.alt = "Poster for " + item.title;
      cover.loading = "lazy";
      cover.referrerPolicy = "no-referrer";
      card.append(cover);
    } else {
      card.append(element("div","trakt-live-poster trakt-live-placeholder","TRAKT"));
    }
    const copy = element("div","trakt-live-copy");
    copy.append(element("p","trakt-live-type",item.type));
    const title = element("h3","trakt-live-title");
    const a = element("a",null,item.title);
    a.href = item.link;
    a.target = "_blank";
    a.rel = "noopener noreferrer";
    title.append(a);
    copy.append(title);
    if (details(item)) copy.append(element("p","trakt-live-details",details(item)));
    if (item.date) {
      const date = element("time","trakt-live-date",
        "Watched " + item.date.toLocaleString("en-GB", {
          day:"numeric",month:"short",year:"numeric",hour:"2-digit",minute:"2-digit"
        }));
      date.dateTime = item.date.toISOString();
      copy.append(date);
    } else if (item.updated) {
      copy.append(element("p","trakt-live-date","Updated " + item.updated));
    }
    card.append(copy);
    return card;
  }

  function snapshotEntries(payload) {
    if (!payload || !Array.isArray(payload.items)) throw new Error("Invalid history data");
    // A null generated_at marks the pre-approval sample, not real watch history.
    if (typeof payload.generated_at !== "string" ||
        Number.isNaN(Date.parse(payload.generated_at))) return [];
    return payload.items.map(normalise).filter(Boolean);
  }

  async function loadSnapshot() {
    const res = await fetch("/assets/data/trakt-history.json", {cache:"no-store",headers:{Accept:"application/json"}});
    if (!res.ok) throw new Error("History unavailable");
    return snapshotEntries(await res.json());
  }

  function pendingNotice(compact) {
    const notice = element("div", "trakt-pending" + (compact ? " trakt-pending-compact" : ""));
    notice.append(element("p", "trakt-pending-label", "COMING SOON"));
    notice.append(element("p", "trakt-pending-message",
      "My Trakt watching history will appear here when the integration is ready."));
    return notice;
  }

  async function render() {
    const about = document.getElementById("trakt-latest-card");
    const journal = document.getElementById("trakt-history");
    if (!about && !journal) return;
    try {
      const items = await loadSnapshot();
      if (about) {
        about.replaceChildren(...(items.length ? [renderCard(items[0], true)] :
          [pendingNotice(true)]));
      }
      if (journal) {
        journal.replaceChildren(...(items.length ?
          items.slice(0, MAX_ENTRIES).map(item => renderCard(item,false)) :
          [pendingNotice(false)]));
      }
    } catch (error) {
      console.warn("Trakt snapshot:", error);
      if (about) about.replaceChildren(pendingNotice(true));
      if (journal) journal.replaceChildren(pendingNotice(false));
    }
  }
  if (typeof module !== "undefined" && module.exports) {
    module.exports = {allowedLink,allowedPoster,normalise,snapshotEntries};
  }
  if (typeof document !== "undefined") {
    if (document.readyState === "loading") document.addEventListener("DOMContentLoaded",render);
    else render();
  }
})();