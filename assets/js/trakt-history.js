/* Trakt watch history and latest-watch card.
   Loads a public JSON snapshot generated by GitHub Actions; no browser-side API credentials.
   All remote strings are inserted with textContent and URLs are restricted. */
(() => {
  "use strict";
  const PROFILE = "https://app.trakt.tv/profile/Pati3nt_Z3ro";
  const MAX_ENTRIES = 30;
  // Trakt watch data comes straight from its public API, as with ListenBrainz.
  // The public Trakt Client ID is served locally; never expose a Client Secret
  // or the private TMDB access token in browser code.
  const TRAKT_API = "https://api.trakt.tv/users/Pati3nt_Z3ro/history?limit=30";
  const PUBLIC_CONFIG = "/assets/data/trakt-public-config.json";
  // GitHub provides pre-resolved TMDB poster URLs (not the viewing history
  // source); the Neocities snapshot is an offline-friendly fallback.
  const LIVE_HISTORY = "https://raw.githubusercontent.com/Schmookey/Website/main/assets/data/trakt-history.json";
  const LOCAL_HISTORY = "/assets/data/trakt-history.json";
  const SAFE_POSTER = /^https:\/\/image\.tmdb\.org\/t\/p\/w(?:92|154|185|200|300|342|500)\/[A-Za-z0-9._-]+\.(?:jpg|jpeg|png|webp)$/i;

  function allowedLink(value) {
    if (typeof value !== "string") return PROFILE;
    try {
      const u = new URL(value);
      return u.protocol === "https:" && u.hostname === "trakt.tv" && !u.username && !u.password
        ? u.href : PROFILE;
    } catch { return PROFILE; }
  }

  function allowedPoster(value) {
    if (typeof value !== "string") return "";
    if (/^\/assets\/images\/trakt\/[A-Za-z0-9._-]+\.(?:jpg|jpeg|png|webp)$/i.test(value)) return value;
    return SAFE_POSTER.test(value) ? value : "";
  }

  function normalise(entry) {
    if (!entry || typeof entry !== "object") return null;
    const title = typeof entry.title === "string" ? entry.title.trim() : "";
    if (!title) return null;
    const detail = typeof entry.episode === "string" ? entry.episode.trim() : "";
    const type = entry.type === "Movie" ? "Movie" : "TV Show";
    const date = typeof entry.watched_at === "string" ? new Date(entry.watched_at) : null;
    return {
      title, type, detail,
      season: Number.isInteger(entry.season) && entry.season >= 0 ? entry.season : null,
      episodeNumber: Number.isInteger(entry.episode_number) && entry.episode_number >= 0 ? entry.episode_number : null,
      year: Number.isInteger(entry.year) && entry.year > 1900 && entry.year < 2200 ? entry.year : null,
      cover: allowedPoster(entry.cover),
      link: allowedLink(entry.link),
      date: date && !Number.isNaN(date.getTime()) ? date : null,
      updated: typeof entry.updated === "string" ? entry.updated : ""
    };
  }

  function element(tag, className, text) {
    const node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined && text !== null) node.textContent = String(text);
    return node;
  }

  function details(item) {
    const parts = [];
    if (item.type === "TV Show" && item.season !== null && item.episodeNumber !== null) {
      parts.push("S" + String(item.season).padStart(2,"0") + "E" + String(item.episodeNumber).padStart(2,"0"));
    } else if (item.type === "TV Show" && item.season !== null) {
      parts.push("Season " + item.season);
    }
    if (item.detail) parts.push(item.detail);
    if (item.year) parts.push(String(item.year));
    return parts.join(" · ");
  }

  function renderCard(item, compact) {
    const card = element("article", compact
      ? "media-card trakt-about-card"
      : "trakt-live-card");
    const copy = element("div", compact ? "media-meta" : "trakt-live-copy");
    if (compact) {
      const art = element("div", "media-thumb-wrap");
      if (item.cover) {
        const img = element("img", "media-thumb");
        img.src = item.cover;
        img.alt = "Poster for " + item.title;
        img.loading = "lazy";
        img.referrerPolicy = "no-referrer";
        art.append(img);
      } else {
        art.setAttribute("aria-hidden", "true");
        art.append(element("span", "trakt-about-thumb", "TRAKT"));
      }
      card.append(art);
    } else if (item.cover) {
      const cover = element("img", "trakt-live-poster");
      cover.src = item.cover;
      cover.alt = "Poster for " + item.title;
      cover.loading = "lazy";
      cover.referrerPolicy = "no-referrer";
      card.append(cover);
    } else {
      card.append(element("div", "trakt-live-poster trakt-live-placeholder", "TRAKT"));
    }
    copy.append(element("p", compact ? "media-label" : "trakt-live-type",
      compact ? "Last Watched" : item.type));
    const title = element(compact ? "p" : "h3", compact ? "media-title" : "trakt-live-title");
    const a = element("a", null, item.title);
    a.href = item.link;
    a.target = "_blank";
    a.rel = "noopener noreferrer";
    title.append(a);
    copy.append(title);
    if (details(item)) copy.append(element("p", compact ? "media-subtitle" : "trakt-live-details", details(item)));
    if (item.date) {
      const date = element("time", compact ? "media-submeta" : "trakt-live-date",
        "Watched " + item.date.toLocaleString("en-GB", {
          day:"numeric",month:"short",year:"numeric",hour:"2-digit",minute:"2-digit"
        }));
      date.dateTime = item.date.toISOString();
      copy.append(date);
    } else if (item.updated) {
      copy.append(element("p", compact ? "media-submeta" : "trakt-live-date", "Updated " + item.updated));
    }
    card.append(copy);
    return card;
  }

  function snapshotEntries(payload) {
    if (!payload || !Array.isArray(payload.items)) throw new Error("Invalid history data");
    // A null generated_at marks the pre-approval sample, not real watch history.
    if (typeof payload.generated_at !== "string" ||
        Number.isNaN(Date.parse(payload.generated_at))) return [];
    return payload.items.map(normalise).filter(Boolean);
  }

  async function fetchSnapshot(url) {
    // A bounded timeout keeps a remote outage from delaying the local fallback.
    const signal = typeof AbortSignal !== "undefined" && typeof AbortSignal.timeout === "function"
      ? AbortSignal.timeout(6000) : undefined;
    const res = await fetch(url, {
      cache: "no-store", credentials: "omit",
      headers: {Accept: "application/json"}, signal
    });
    if (!res.ok) throw new Error("History unavailable");
    const entries = snapshotEntries(await res.json());
    if (!entries.length) throw new Error("No usable history");
    return entries;
  }

  async function fetchPosterSnapshot() {
    try {
      return await fetchSnapshot(LIVE_HISTORY);
    } catch {
      return fetchSnapshot(LOCAL_HISTORY);
    }
  }

  function makePosterMap(items) {
    const posters = new Map();
    for (const item of items) {
      if (!item.cover) continue;
      // Match by Trakt URL first, then by type and title for unusual slugs.
      posters.set(item.link, item.cover);
      posters.set(item.type + "|" + item.title.toLocaleLowerCase("en-GB"), item.cover);
    }
    return posters;
  }

  function normaliseTraktRow(row, posters = new Map()) {
    if (!row || typeof row !== "object") return null;
    const movie = row.type === "movie";
    if (!movie && row.type !== "episode" && row.type !== "show") return null;
    const media = movie ? row.movie : row.show;
    if (!media || typeof media.title !== "string" || !media.title.trim()) return null;
    const ids = media.ids && typeof media.ids === "object" ? media.ids : {};
    const slug = typeof ids.slug === "string" && /^[a-z0-9-]+$/i.test(ids.slug)
      ? ids.slug : "";
    const link = slug
      ? "https://trakt.tv/" + (movie ? "movies/" : "shows/") + encodeURIComponent(slug)
      : PROFILE;
    const type = movie ? "Movie" : "TV Show";
    const title = media.title.trim();
    const poster = posters.get(link) || posters.get(type + "|" + title.toLocaleLowerCase("en-GB")) || "";
    const episode = row.episode && typeof row.episode === "object" ? row.episode : {};
    return normalise({
      title, type, link, cover: poster, year: media.year,
      episode: movie ? "" : episode.title,
      season: movie ? null : episode.season,
      episode_number: movie ? null : episode.number,
      watched_at: row.watched_at
    });
  }

  async function fetchDirectHistory() {
    const settings = await fetch(PUBLIC_CONFIG, {
      cache: "no-store", credentials: "omit", headers: {Accept:"application/json"}
    });
    if (!settings.ok) throw new Error("Public Trakt configuration unavailable");
    const config = await settings.json();
    const id = config && config.client_id;
    if (typeof id !== "string" || !/^[A-Za-z0-9_.-]{8,256}$/.test(id)) {
      throw new Error("Public Trakt Client ID missing or invalid");
    }
    const signal = typeof AbortSignal !== "undefined" && typeof AbortSignal.timeout === "function"
      ? AbortSignal.timeout(6000) : undefined;
    const response = await fetch(TRAKT_API, {
      credentials: "omit", cache: "no-store", signal,
      headers: {
        Accept: "application/json",
        "trakt-api-version": "2",
        "trakt-api-key": id
      }
    });
    if (!response.ok) throw new Error("Trakt public history unavailable");
    const rows = await response.json();
    if (!Array.isArray(rows) || !rows.length) throw new Error("Empty Trakt public history");
    return rows;
  }

  async function loadSnapshot() {
    // These calls run together so TMDB poster metadata doesn't delay the
    // direct Trakt request. Neither API credential is sent to GitHub.
    const [direct, cached] = await Promise.allSettled([
      fetchDirectHistory(), fetchPosterSnapshot()
    ]);
    if (direct.status === "fulfilled") {
      const posters = cached.status === "fulfilled" ? makePosterMap(cached.value) : new Map();
      const items = direct.value.map(row => normaliseTraktRow(row, posters)).filter(Boolean);
      if (items.length) return items;
    }
    // CORS, invalid config, or a temporary API failure: preserve a working widget.
    if (cached.status === "fulfilled") return cached.value;
    throw new Error("Trakt history temporarily unavailable");
  }

  function pendingNotice(compact) {
    if (compact) {
      const card = element("article", "media-card trakt-about-card trakt-pending");
      const art = element("div", "media-thumb-wrap");
      art.setAttribute("aria-hidden", "true");
      art.append(element("span", "trakt-about-thumb", "TRAKT"));
      card.append(art);
      const copy = element("div", "media-meta");
      copy.append(element("p", "media-label", "Last Watched"));
      copy.append(element("p", "media-title", "Coming Soon"));
      copy.append(element("p", "media-subtitle",
        "My watching history will appear here once the integration is ready."));
      card.append(copy);
      return card;
    }
    const notice = element("div", "trakt-pending");
    notice.append(element("p", "trakt-pending-label", "COMING SOON"));
    notice.append(element("p", "trakt-pending-message",
      "My Trakt watching history will appear here when the integration is ready."));
    return notice;
  }

  async function render() {
    const about = document.getElementById("trakt-latest-card");
    const journal = document.getElementById("trakt-history");
    if (!about && !journal) return;
    try {
      const items = await loadSnapshot();
      if (about) {
        about.replaceChildren(...(items.length ? [renderCard(items[0], true)] :
          [pendingNotice(true)]));
      }
      if (journal) {
        journal.replaceChildren(...(items.length ?
          items.slice(0, MAX_ENTRIES).map(item => renderCard(item,false)) :
          [pendingNotice(false)]));
      }
    } catch (error) {
      console.warn("Trakt snapshot:", error);
      if (about) about.replaceChildren(pendingNotice(true));
      if (journal) journal.replaceChildren(pendingNotice(false));
    }
  }
  if (typeof module !== "undefined" && module.exports) {
    module.exports = {allowedLink,allowedPoster,normalise,snapshotEntries,normaliseTraktRow,makePosterMap,loadSnapshot};
  }
  if (typeof document !== "undefined") {
    if (document.readyState === "loading") document.addEventListener("DOMContentLoaded",render);
    else render();
    // Recheck while the page remains open, without polling Trakt directly.
    setInterval(() => {
      if (document.visibilityState !== "hidden") render();
    }, 30 * 60 * 1000);
  }
})();